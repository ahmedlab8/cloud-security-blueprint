#!/usr/bin/env python3
"""Render Gatekeeper ConstraintTemplates from the tested Rego sources.

The Rego in gatekeeper/rego/ is the single source of truth (unit-tested with `opa test`).
This script embeds it into ConstraintTemplate manifests so what is tested is exactly
what is deployed.

    python3 generate.py          # (re)write templates/*.yaml
    python3 generate.py --check  # exit 1 if templates are stale (used in CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REGO = HERE / "rego"
OUT = HERE / "templates"

# kind -> (rego file, uses shared lib, description)
TEMPLATES = {
    "K8sBlockRootContainers": ("block_root.rego", True, "Requires containers to run as non-root (runAsNonRoot / non-zero UID)."),
    "K8sBlockPrivilegedContainers": (
        "block_privileged.rego",
        True,
        "Blocks privileged containers, privilege escalation and host namespaces.",
    ),
    "K8sDisallowLatestTag": ("disallow_latest.rego", True, "Blocks images using the :latest tag or no tag at all."),
    "K8sRequireResourceLimits": ("require_limits.rego", True, "Requires CPU and memory requests and limits on every container."),
    "K8sBlockPublicLoadBalancer": (
        "block_public_lb.rego",
        False,
        "Blocks internet-facing LoadBalancer Services; only internal load balancers are allowed.",
    ),
}


def indent(text: str, n: int) -> str:
    pad = " " * n
    return "\n".join(pad + line if line else "" for line in text.rstrip("\n").split("\n"))


def render(kind: str, rego_file: str, uses_lib: bool, description: str) -> str:
    rego = (REGO / rego_file).read_text()
    lib = (REGO / "lib_workload.rego").read_text()
    libs = ""
    if uses_lib:
        libs = "      libs:\n        - |\n" + indent(lib, 10) + "\n"
    return (
        "# GENERATED by policies/opa/gatekeeper/generate.py from rego/"
        f"{rego_file} - do not edit by hand.\n"
        "apiVersion: templates.gatekeeper.sh/v1\n"
        "kind: ConstraintTemplate\n"
        "metadata:\n"
        f"  name: {kind.lower()}\n"
        "  annotations:\n"
        f'    description: "{description}"\n'
        "spec:\n"
        "  crd:\n"
        "    spec:\n"
        "      names:\n"
        f"        kind: {kind}\n"
        "  targets:\n"
        "    - target: admission.k8s.gatekeeper.sh\n"
        "      rego: |\n"
        f"{indent(rego, 8)}\n"
        f"{libs}"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = ap.parse_args()

    OUT.mkdir(exist_ok=True)
    stale = []
    for kind, (rego_file, uses_lib, desc) in TEMPLATES.items():
        path = OUT / f"{kind.lower()}.yaml"
        content = render(kind, rego_file, uses_lib, desc)
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(path.name)
        else:
            path.write_text(content)
            print(f"wrote {path.relative_to(HERE)}")
    if stale:
        print("stale templates (run generate.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
