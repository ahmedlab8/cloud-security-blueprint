#!/usr/bin/env python3
"""Wrap rules/security-alerts.yml in a PrometheusRule CRD for kube-prometheus-stack."""

from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
rules = yaml.safe_load((HERE / "rules" / "security-alerts.yml").read_text())
doc = {
    "apiVersion": "monitoring.coreos.com/v1",
    "kind": "PrometheusRule",
    "metadata": {"name": "csb-security-alerts", "namespace": "monitoring", "labels": {"release": "kube-prometheus-stack"}},
    "spec": rules,
}
header = "# GENERATED by build_prometheusrule.py from rules/security-alerts.yml - do not edit.\n"
(HERE / "prometheusrule.yaml").write_text(header + yaml.safe_dump(doc, sort_keys=False, width=200))
print("wrote prometheusrule.yaml")
